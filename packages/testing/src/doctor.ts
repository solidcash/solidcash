import fs from 'fs';
import path from 'path';
import type { ResolvedConfig } from './config.js';
import { solidcashArtifactsPath } from './artifact-paths.js';

export interface DoctorFinding {
  severity: 'error' | 'warning' | 'info';
  code: string;
  message: string;
  path?: string;
}

function generatedFiles(directory: string): string[] {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { recursive: true, encoding: 'utf8' })
    .filter((entry) => entry.endsWith('.ts')).map((entry) => path.join(directory, entry));
}

/** Read-only project health and migration diagnostics, suitable for editors and CI. */
export function diagnoseProject(config: ResolvedConfig, projectDir = process.cwd()): DoctorFinding[] {
  const findings: DoctorFinding[] = [];
  const contracts = path.resolve(config.paths.contracts);
  const artifacts = solidcashArtifactsPath(config.paths.artifacts);
  if (!fs.existsSync(contracts)) findings.push({
    severity: 'error', code: 'contracts-missing', path: contracts, message: 'Configured contracts directory does not exist.',
  });
  if (!fs.existsSync(artifacts)) findings.push({
    severity: 'warning', code: 'artifacts-missing', path: artifacts, message: 'No compiled artifacts found; run `solidhat compile`.',
  });
  const outputPaths = new Set<string>();
  for (const target of config.typegen.targets) {
    const output = path.resolve(target.outDir);
    if (outputPaths.has(output)) findings.push({
      severity: 'error', code: 'typegen-output-collision', path: output,
      message: 'Multiple TypeChain targets use the same output directory.',
    });
    outputPaths.add(output);
    if (output === contracts || output.startsWith(`${contracts}${path.sep}`)) findings.push({
      severity: 'error', code: 'typegen-inside-sources', path: output,
      message: 'Generated bindings must not be written inside the contract source tree.',
    });
    for (const file of generatedFiles(output)) {
      const source = fs.readFileSync(file, 'utf8');
      if (path.basename(file) !== 'registry.ts' && path.basename(file) !== 'index.ts'
        && !source.includes('Autogenerated by SolidHat')) findings.push({
        severity: 'warning', code: 'manual-generated-file', path: file,
        message: 'File inside a generated output tree lacks the SolidHat generated marker.',
      });
    }
  }
  const packageFile = path.join(projectDir, 'package.json');
  if (fs.existsSync(packageFile)) {
    const pkg = JSON.parse(fs.readFileSync(packageFile, 'utf8')) as {
      dependencies?: Record<string, string>; devDependencies?: Record<string, string>;
    };
    const dependencies = { ...pkg.dependencies, ...pkg.devDependencies };
    if (dependencies.hardhat && !config.typegen.targets.length) findings.push({
      severity: 'info', code: 'hardhat-typegen-disabled',
      message: 'Hardhat detected; enable ethers5 or ethers6 typegen for TypeChain import compatibility.',
    });
  }
  if (findings.length === 0) findings.push({ severity: 'info', code: 'healthy', message: 'No SolidHat project issues found.' });
  return findings;
}
