/**
 * Golden vectors for the witness block codec (specification sections 5.1-5.3, 6 and 16).
 *
 * `hex` is the one byte image the wire format allows for the fields beside it, computed outside the module under
 * test from the specification. The block fields are the same data in structured form, so a test can both build the
 * block and check the bytes the codec produces.
 */

import { CATEGORY_A, LOADER_CODE_A, LOADER_CODE_B, VALIDATOR_REDEEM_SCRIPT_A } from './identity.js';

/** The absent index, written as the literal the wire format uses. */
export const INDEX_NONE_SENTINEL = 65535;

const h = (...parts: string[]): string => parts.join('');

export interface CallVector {
  readonly kind: number;
  readonly target: string;
  readonly value: string;
  readonly calleeRef: number;
  readonly argsHash: string;
  readonly result: string;
}

export interface RecordEntryVector {
  readonly in: number;
  readonly out: number;
  readonly viewIn: string;
  readonly viewOut: string;
}

export interface BlockVector {
  readonly hex: string;
  readonly kind: number;
  readonly callerRef: number;
  readonly originRef: number;
  readonly validatorRef: number;
  readonly sender: string;
  readonly self: string;
  readonly value: string;
  readonly retval: string;
  readonly calls: readonly CallVector[];
  readonly segments: readonly (readonly RecordEntryVector[])[];
  readonly events: readonly number[];
  readonly sends: readonly number[];
}

