import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const websiteRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const artifactPath = resolve(websiteRoot, '../packages/utils/src/artifact.ts');
const outputPath = resolve(websiteRoot, 'docs/reference/message-bus-artifact.md');
const source = await readFile(artifactPath, 'utf8');

function constant(name) {
  const match = source.match(new RegExp(`export const ${name} = ([^;]+);`));
  if (!match) throw new Error(`Missing ${name} in ${artifactPath}`);
  return match[1].replaceAll("'", '').trim();
}

function messageBusFields() {
  const start = source.indexOf('  messageBus?: {');
  const end = source.indexOf('\n    route: AbiFunction;', start);
  if (start < 0 || end < 0) throw new Error(`Missing Artifact.messageBus in ${artifactPath}`);
  const block = source.slice(start, end);
  const names = [...block.matchAll(/^    ([A-Za-z][A-Za-z0-9]*)(?:\?)?: ([^;{]+);/gm)]
    .map(([, name, type]) => [name, type.trim()]);
  return names;
}

const fields = messageBusFields();
const markdown = `---
title: Message Bus Artifact Reference
---

<!-- Generated by scripts/generate-message-bus-reference.mjs from packages/utils/src/artifact.ts. -->

This page is generated from the compiler's shared artifact schema. Run \`yarn docs:generate\` in \`website\`
after changing message-bus artifact fields or limits.

## Protocol limits

| Artifact source | Value |
| --- | ---: |
| \`SINGLE_TX_BUS_MAX_PARTICIPANTS\` | ${constant('SINGLE_TX_BUS_MAX_PARTICIPANTS')} |
| \`SINGLE_TX_BUS_MAX_ROWS\` | ${constant('SINGLE_TX_BUS_MAX_ROWS')} |
| \`MAX_MESSAGE_BUS_BLOB_BYTES\` | ${constant('MAX_MESSAGE_BUS_BLOB_BYTES')} bytes |
| \`SINGLE_TX_BUS_DOMAIN_HEX\` | \`${constant('SINGLE_TX_BUS_DOMAIN_HEX')}\` |

These are admission ceilings. Finalized transaction size and BCH-2026 VM preflight can impose a smaller limit for
a resource-heavy graph.

## \`Artifact.messageBus\` fields

| Field | Schema type |
| --- | --- |
${fields.map(([name, type]) => `| \`${name}\` | \`${type.replaceAll('|', '\\|')}\` |`).join('\n')}

The nested \`singleTransactionBus\` record publishes carrier placement and participant/row bounds. The
\`verifierProgram\` record is deployment material for the artifact-specialized self-preserving verifier; it is not
an execution controller.
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, markdown);
